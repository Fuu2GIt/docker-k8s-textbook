import os
import time
from http.server import BaseHTTPRequestHandler, HTTPServer

import psycopg


def connect():
    last_error = None
    for _ in range(30):
        try:
            return psycopg.connect(
                host=os.environ["PGHOST"],
                port=os.environ.get("PGPORT", "5432"),
                user=os.environ["PGUSER"],
                password=os.environ["PGPASSWORD"],
                dbname=os.environ["PGDATABASE"],
            )
        except psycopg.OperationalError as error:
            last_error = error
            time.sleep(1)
    raise last_error


def prepare(connection):
    connection.execute(
        "CREATE TABLE IF NOT EXISTS memos (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body text NOT NULL)"
    )
    connection.commit()


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        with self.server.connection.cursor() as cursor:
            cursor.execute("SELECT id, body FROM memos ORDER BY id")
            rows = cursor.fetchall()
        lines = [f"{row[0]} {row[1]}" for row in rows]
        text = "\n".join(lines)
        if text:
            text += "\n"
        body = text.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", "0"))
        text = self.rfile.read(length).decode("utf-8").strip()
        if text == "":
            self.send_error(400, "empty")
            return
        with self.server.connection.cursor() as cursor:
            cursor.execute(
                "INSERT INTO memos (body) VALUES (%s)",
                (text,),
            )
        self.server.connection.commit()
        message = "saved\n".encode("utf-8")
        self.send_response(201)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(message)))
        self.end_headers()
        self.wfile.write(message)


class MemoServer(HTTPServer):
    def __init__(self, address, handler):
        super().__init__(address, handler)
        self.connection = connect()
        prepare(self.connection)


def main():
    port = int(os.environ.get("PORT", "8000"))
    server = MemoServer(("0.0.0.0", port), Handler)
    print(f"listening on {port}", flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
